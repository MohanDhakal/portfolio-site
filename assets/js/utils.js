/* ============================================================
   Shared utilities: data loading, path helpers, rendering bits.
   No build step is required to run the site locally or on
   GitHub Pages — data/articles.json is generated by
   scripts/build-index.js (see README) and committed, or
   regenerated automatically by the GitHub Actions workflow.
   ============================================================ */

// Resolve paths correctly whether the site is served from a
// domain root (username.github.io) or a project subpath
// (username.github.io/repo-name).
const SITE_ROOT = (() => {
  const path = window.location.pathname;
  const base = path.substring(0, path.lastIndexOf("/") + 1);
  // Walk up until we find a directory that contains data/articles.json's
  // known parent structure. Simplest reliable approach for this project:
  // every HTML page lives at the repo root, so the page's own directory
  // *is* the site root.
  return base;
})();

function siteUrl(relativePath) {
  return SITE_ROOT + relativePath.replace(/^\//, "");
}

let _indexPromise = null;
function loadIndex() {
  if (!_indexPromise) {
    _indexPromise = fetch(siteUrl("data/articles.json"), { cache: "no-cache" })
      .then((r) => {
        if (!r.ok) throw new Error("Could not load data/articles.json (" + r.status + ")");
        return r.json();
      })
      .catch((err) => {
        console.error(err);
        return { articles: [], categories: [], highlights: [], generatedAt: null };
      });
  }
  return _indexPromise;
}

// Deterministic badge color tone (1-4) from a category name, so the
// same category always gets the same tone without a lookup table.
function toneForCategory(name) {
  let hash = 0;
  for (let i = 0; i < name.length; i++) hash = (hash * 31 + name.charCodeAt(i)) >>> 0;
  return (hash % 4) + 1;
}

function formatDate(iso) {
  if (!iso) return null;
  const d = new Date(iso + (iso.length === 10 ? "T00:00:00" : ""));
  if (isNaN(d.getTime())) return iso;
  return d.toLocaleDateString(undefined, { year: "numeric", month: "short", day: "numeric" });
}

function articleUrl(article) {
  return siteUrl("article.html") + "?path=" + encodeURIComponent(article.path);
}

function categoryUrl(category) {
  return siteUrl("articles.html") + "?category=" + encodeURIComponent(category);
}

// Renders a single article card. `variant` = "grid" (articles page) or
// "feature" (homepage highlights) — currently share the same markup.
function renderCard(article) {
  const tone = toneForCategory(article.category);
  const dateStr = formatDate(article.date);
  const metaBits = [`${article.readingTime} min read`];
  if (dateStr) metaBits.unshift(dateStr);

  const el = document.createElement("article");
  el.className = "card";
  el.innerHTML = `
    <a class="badge tone-${tone}" href="${categoryUrl(article.category)}">${escapeHtml(article.category)}</a>
    <h3><a href="${articleUrl(article)}">${escapeHtml(article.title)}</a></h3>
    <p class="excerpt">${escapeHtml(article.excerpt)}</p>
    <div class="card-meta">${metaBits.map((b, i) => (i > 0 ? `<span class="dot"></span>${b}` : b)).join("")}</div>
    <a class="read-link" href="${articleUrl(article)}">Read article &rarr;</a>
  `;
  return el;
}

function escapeHtml(str) {
  if (!str) return "";
  return str.replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[c]));
}

// ---------------- Mobile nav + search overlay wiring ----------------
// Shared by every page; safe no-ops if the elements aren't present.
document.addEventListener("DOMContentLoaded", () => {
  const toggle = document.querySelector(".nav-toggle");
  const links = document.querySelector(".nav-links");
  if (toggle && links) {
    toggle.addEventListener("click", () => links.classList.toggle("open"));
  }

  const searchBtn = document.querySelector(".nav-search-btn");
  const overlay = document.querySelector(".search-overlay");
  const input = document.querySelector(".search-input");
  const resultsBox = document.querySelector(".search-results");

  function openSearch() {
    if (!overlay) return;
    overlay.classList.add("open");
    input.value = "";
    resultsBox.innerHTML = "";
    setTimeout(() => input.focus(), 10);
  }
  function closeSearch() {
    if (!overlay) return;
    overlay.classList.remove("open");
  }

  if (searchBtn) searchBtn.addEventListener("click", openSearch);
  if (overlay) {
    overlay.addEventListener("click", (e) => { if (e.target === overlay) closeSearch(); });
  }
  document.addEventListener("keydown", (e) => {
    if ((e.key === "k" || e.key === "/") && (e.metaKey || e.ctrlKey || e.key === "/")) {
      if (e.key === "/" && document.activeElement && ["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) return;
      e.preventDefault();
      openSearch();
    }
    if (e.key === "Escape") closeSearch();
  });

  if (input) {
    let allArticles = [];
    loadIndex().then((data) => { allArticles = data.articles || []; });

    input.addEventListener("input", () => {
      const q = input.value.trim().toLowerCase();
      resultsBox.innerHTML = "";
      if (!q) return;
      const matches = allArticles.filter((a) => {
        const hay = [a.title, a.category, a.description, a.excerpt, (a.tags || []).join(" ")]
          .join(" ").toLowerCase();
        return hay.includes(q);
      }).slice(0, 8);

      if (matches.length === 0) {
        resultsBox.innerHTML = `<div class="search-empty">No articles match "${escapeHtml(input.value)}".</div>`;
        return;
      }
      matches.forEach((a) => {
        const a_el = document.createElement("a");
        a_el.className = "search-result";
        a_el.href = articleUrl(a);
        a_el.innerHTML = `<div class="sr-title">${escapeHtml(a.title)}</div><div class="sr-meta">${escapeHtml(a.category)} &middot; ${a.readingTime} min read</div>`;
        resultsBox.appendChild(a_el);
      });
    });
  }
});
